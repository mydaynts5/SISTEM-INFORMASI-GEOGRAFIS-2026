-- Membuat Tabel Users
CREATE TABLE users (
    id SERIAL PRIMARY KEY,
    email VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL
);

-- Membuat Indeks GiST pada Kolom Geometri Tabel fasilitas_publik
CREATE INDEX idx_fasilitas_publik_geom 
ON fasilitas_publik 
USING GIST (geom);

-- Membuat Indeks GiST pada Kolom Geometri Tabel jalan
CREATE INDEX idx_jalan_geom 
ON jalan 
USING GIST (geom);

-- Membuat Indeks GiST pada Kolom Geometri Tabel wilayah
CREATE INDEX idx_wilayah_geom 
ON wilayah 
USING GIST (geom);

-- Membuat Indeks GiST Khusus pada Cast Geography (Optimasi ST_DWithin / Jarak)
CREATE INDEX idx_fasilitas_publik_geog 
ON fasilitas_publik 
USING GIST ((geom::geography));

-- Memverifikasi Indeks yang Sukses Terbuat
SELECT indexname, tablename
FROM pg_indexes
WHERE schemaname = 'public' 
  AND tablename IN ('fasilitas_publik', 'jalan', 'wilayah');